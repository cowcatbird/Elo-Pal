// Rebuilds the offline index entirely from the bundled, pinned CC0 TSV sources.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { Chess } from '../vendor/chess.js';

const folder = fileURLToPath(new URL('../vendor/openings/', import.meta.url));
const sourceFolder = path.join(folder, 'source');
const revision = 'a6189a30dc273ccb21fc2536a9a2fefd5592a67a';
const sourceFiles = ['a.tsv', 'b.tsv', 'c.tsv', 'd.tsv', 'e.tsv', 'COPYING.txt', 'README.md'];
if (process.argv.includes('--download')) {
  await mkdir(sourceFolder, { recursive: true });
  for (const name of sourceFiles) {
    const response = await fetch(`https://raw.githubusercontent.com/lichess-org/chess-openings/${revision}/${name}`, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok) throw new Error(`Download failed for ${name}: ${response.status}`);
    await writeFile(path.join(sourceFolder, name), Buffer.from(await response.arrayBuffer()));
  }
  await writeFile(path.join(sourceFolder, 'REVISION'), revision + '\n');
}
if ((await readFile(path.join(sourceFolder, 'REVISION'), 'utf8')).trim() !== revision) throw new Error('Opening source revision does not match this builder.');
const rows = [], nodes = [], nodeIds = new Map(), paths = [], hashes = {};
const key = fen => fen.split(' ').slice(0, 4).join(' ');
const node = (fen, row, ply) => {
  const epd = key(fen);
  let id = nodeIds.get(epd);
  if (id === undefined) {
    id = nodes.length; nodeIds.set(epd, id);
    nodes.push({ key: epd, named: [], label: -1, labelDistance: Infinity, row, ply, maxPly: ply, edges: new Map() });
  }
  const current = nodes[id];
  if (ply < current.ply) { current.row = row; current.ply = ply; }
  current.maxPly = Math.max(current.maxPly, ply);
  return id;
};
for (const name of sourceFiles) {
  const content = await readFile(path.join(sourceFolder, name));
  hashes[name] = createHash('sha256').update(content).digest('hex');
  if (!name.endsWith('.tsv')) continue;
  const lines = content.toString('utf8').replace(/^\uFEFF/, '').trim().split(/\r?\n/);
  if (lines.shift() !== 'eco\tname\tpgn') throw new Error(`Unexpected columns in ${name}`);
  for (const line of lines) {
    const [eco, openingName, pgn, ...extra] = line.split('\t');
    if (!/^[A-E]\d\d$/.test(eco) || !openingName || !pgn || extra.length) throw new Error(`Malformed source row: ${line}`);
    const board = new Chess();
    board.loadPgn(pgn);
    const history = board.history({ verbose: true });
    const uci = history.map(move => move.from + move.to + (move.promotion || ''));
    const rowId = rows.length;
    rows.push([eco, openingName, pgn, uci]);
    const pathIds = [node(new Chess().fen(), rowId, 0)];
    history.forEach((move, index) => {
      const next = node(move.after, rowId, index + 1);
      const previous = nodes[pathIds.at(-1)];
      const edge = previous.edges.get(uci[index]);
      if (edge) edge[3]++;
      else previous.edges.set(uci[index], [uci[index], move.san, next, 1]);
      pathIds.push(next);
    });
    nodes[pathIds.at(-1)].named.push(rowId);
    paths.push(pathIds);
  }
}
// Labels on intermediate positions come only from an earlier named position,
// never from a future variation that has not been played yet.
for (let row = 0; row < paths.length; row++) {
  let lastLabel = -1, lastNamedPly = 0;
  paths[row].forEach((nodeId, ply) => {
    const current = nodes[nodeId];
    if (current.named.length) {
      const compatible = current.named.filter(id => rows[id][3].every((move, index) => rows[row][3][index] === move));
      lastLabel = (compatible.length ? compatible : current.named).slice().sort((a, b) => rows[b][1].length - rows[a][1].length || a - b)[0];
      lastNamedPly = ply;
    }
    if (lastLabel >= 0 && ply - lastNamedPly < current.labelDistance) {
      current.label = lastLabel;
      current.labelDistance = ply - lastNamedPly;
    }
  });
}
const data = { revision, rows, positions: nodes.map(current => [current.key, current.label, current.named, current.row, current.ply,
  [...current.edges.values()].sort((a, b) => b[3] - a[3] || a[0].localeCompare(b[0])), current.maxPly]) };
const indexText = `// Generated by scripts/build-openings.mjs from the pinned Lichess CC0 dataset.\nexport default ${JSON.stringify(data)};\n`;
await writeFile(path.join(folder, 'index.js'), indexText);
const metadata = {
  source: 'https://github.com/lichess-org/chess-openings', revision, license: 'CC0-1.0',
  sourceTree: `https://github.com/lichess-org/chess-openings/tree/${revision}`,
  openingCount: rows.length, positionCount: nodes.length, namedPositionCount: nodes.filter(n => n.named.length).length,
  ecoCodes: [...new Set(rows.map(row => row[0]))].sort(),
  sourceSha256: hashes, indexSha256: createHash('sha256').update(indexText).digest('hex'),
  build: 'node scripts/build-openings.mjs',
  refreshPinnedSources: 'node scripts/build-openings.mjs --download',
  matching: 'Legal move replay; position key is piece placement, turn, castling rights, and legal en-passant square. Names are assigned only after their named position is reached.',
};
await writeFile(path.join(folder, 'provenance.json'), JSON.stringify(metadata, null, 2) + '\n');
console.log(`Built ${rows.length} opening lines, ${nodes.length} positions, ${metadata.ecoCodes.length} ECO codes from ${revision}.`);
